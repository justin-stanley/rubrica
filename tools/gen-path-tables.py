#!/usr/bin/env python3
"""Generates crates/rubrica-site/src/path_tables.rs, two Unicode tables for
page paths (rubrica-site `source.rs`):

- CASE_FOLD: full Unicode case folding (CaseFolding.txt statuses C and F),
  as Python's str.casefold() applies it, for the duplicate-URL fold: two
  paths equal under NFD(casefold(NFD(x))) are one file on APFS (`ſ` and `s`,
  the Kelvin sign and `k`);
- FORMAT: the code points of general category Cf (format characters, the
  bidi controls among them), which no page path may contain.

The Unicode version is Python's (unicodedata.unidata_version), written into
the file and pinned by a test. Not a build step; run by hand, needing no
package:

  python3 tools/gen-path-tables.py <rubrica checkout>
"""
import sys
import unicodedata

if len(sys.argv) != 2:
    raise SystemExit("usage: gen-path-tables.py <rubrica checkout>")
repo = sys.argv[1]


def chars():
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        yield c


fold = []
for c in chars():
    f = chr(c).casefold()
    if f != chr(c):
        fold.append((c, f))

fmt = []
start = None
for c in range(0x110001):
    inside = c < 0x110000 and not (0xD800 <= c <= 0xDFFF) and unicodedata.category(chr(c)) == "Cf"
    if inside and start is None:
        start = c
    if not inside and start is not None:
        fmt.append((start, c - 1))
        start = None


def hexc(c):
    return "0x%04X" % c


def rust_str(s):
    return '"' + "".join("\\u{%X}" % ord(ch) for ch in s) + '"'


out = []
out.append("// @generated by tools/gen-path-tables.py under Python %s (Unicode %s); do not edit."
           % (sys.version.split()[0], unicodedata.unidata_version))
out.append("//! Unicode tables for page paths: full case folding and the format")
out.append("//! characters (Cf).")
out.append("")
out.append("/// The Unicode version of the Python the tables came from, pinned by a test.")
out.append("#[cfg(test)]")
out.append('pub(crate) const UNICODE_VERSION: &str = "%s";' % unicodedata.unidata_version)
out.append("")
out.append("/// Full case folding (statuses C and F): each code point that folds, and")
out.append("/// what it folds to, sorted by code point.")
out.append("pub(crate) const CASE_FOLD: &[(u32, &str)] = &[")
for c, f in fold:
    out.append("    (%s, %s)," % (hexc(c), rust_str(f)))
out.append("];")
out.append("")
out.append("/// General category Cf, as sorted inclusive ranges.")
out.append("pub(crate) const FORMAT: &[(u32, u32)] = &[")
for a, b in fmt:
    out.append("    (%s, %s)," % (hexc(a), hexc(b)))
out.append("];")
out.append("")

path = repo + "/crates/rubrica-site/src/path_tables.rs"
with open(path, "w", encoding="utf-8") as fh:
    fh.write("\n".join(out))
print("%s: %d folds, %d Cf ranges (Unicode %s)" % (path, len(fold), len(fmt), unicodedata.unidata_version))
