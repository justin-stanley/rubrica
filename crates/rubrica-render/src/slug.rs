    /// Duplicates cost a bounded number of probes each, not one per earlier
    /// duplicate: 30,000 `# a` headings took 16.2 s when every heading probed
    /// `a-1`, `a-2`, … from 1.
    #[test]
    fn duplicate_headings_probe_a_bounded_number_of_suffixes() {
        const N: usize = 30_000;
        let mut slugs = Slugs::new();
        for i in 0..N {
            let id = slugs.heading_id("a").id;
            let want = if i == 0 {
                "a".to_owned()
            } else {
                format!("a-{i}")
            };
            assert_eq!(id, want);
        }
        assert!(
            slugs.probes <= 2 * N as u64,
            "{} probes for {N} headings",
            slugs.probes
        );
    }

