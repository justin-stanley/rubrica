//! The generated advance-width table: what it names, what it holds, how it is read.

use std::hint::black_box;

use rubrica_diagram::{
    advance, text_width, ASCENT, AVERAGE, CAP_HEIGHT, DESCENT, FONT_TTF_SHA256, FONT_VERSION,
    FONT_WOFF2_SHA256, UNITS_PER_EM,
};

fn is_sha256_hex(s: &str) -> bool {
    s.len() == 64
        && s.bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

#[test]
fn the_table_is_generated_and_names_its_font() {
    let widths = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/src/widths.rs"));
    assert!(
        widths.starts_with("// @generated by tools/gen-font-widths from Inter 4.1"),
        "assertion failed: widths.starts_with(\"// @generated by tools/gen-font-widths from Inter 4.1\")"
    );
    assert_eq!(FONT_VERSION, "4.1");
    assert!(
        is_sha256_hex(FONT_TTF_SHA256),
        "ttf hash: {FONT_TTF_SHA256:?}"
    );
    assert!(
        is_sha256_hex(FONT_WOFF2_SHA256),
        "woff2 hash: {FONT_WOFF2_SHA256:?}"
    );
    assert_ne!(FONT_TTF_SHA256, FONT_WOFF2_SHA256);
}

#[test]
fn every_range_has_one_advance_per_code_point() {
    assert!(advance(' ') > 0, "assertion failed: advance(' ') > 0");
    let ranges = [
        (0x0020u32, 0x007Eu32),
        (0x00A0, 0x00FF),
        (0x0100, 0x017F),
        (0x0180, 0x024F),
        (0x0370, 0x03FF),
        (0x0400, 0x04FF),
        (0x1E00, 0x1EFF),
        (0x2000, 0x206F),
    ];
    for (first, last) in ranges {
        for cp in first..=last {
            let c = char::from_u32(cp).expect("a char");
            assert!(advance(c) <= 3000, "U+{cp:04X} has advance {}", advance(c));
        }
    }
}

#[test]
fn wide_letters_are_wider_than_narrow_ones() {
    assert!(
        advance('W') > advance('i'),
        "assertion failed: advance('W') > advance('i')"
    );
    assert!(
        advance('M') > advance('l'),
        "assertion failed: advance('M') > advance('l')"
    );
    assert!(
        advance('Ж') > advance('\u{0456}'),
        "assertion failed: advance('Ж') > advance('і')"
    );
}

#[test]
fn outside_the_ranges_is_the_average_and_the_average_is_the_ascii_mean() {
    // black_box: the constants are compile-time values, and clippy would fold the comparisons.
    let average = black_box(AVERAGE);
    assert!(average > 0, "assertion failed: AVERAGE > 0");
    assert_eq!(advance('中'), average);
    assert_eq!(advance('\u{1F600}'), average);
    let (sum, n) = (' '..='~').fold((0u32, 0u32), |(s, n), c| (s + u32::from(advance(c)), n + 1));
    assert_eq!(u32::from(average), (sum + n / 2) / n);
}

#[test]
fn text_width_is_the_sum_of_advances() {
    assert!(
        text_width("Wi") > 0,
        "assertion failed: text_width(\"Wi\") > 0"
    );
    assert_eq!(text_width(""), 0);
    assert_eq!(
        text_width("Wi"),
        u32::from(advance('W')) + u32::from(advance('i'))
    );
}

#[test]
fn the_vertical_metrics_are_plausible() {
    let (ascent, descent, cap) = (black_box(ASCENT), black_box(DESCENT), black_box(CAP_HEIGHT));
    assert!(0 < cap, "assertion failed: 0 < CAP_HEIGHT");
    assert!(cap < ascent);
    assert!(0 < descent && descent < ascent);
    assert!(u32::from(ascent) + u32::from(descent) < 2 * UNITS_PER_EM);
}
