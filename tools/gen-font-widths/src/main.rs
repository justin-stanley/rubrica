//! Writes `crates/rubrica-diagram/src/widths.rs`: Inter's advance widths at 1,000 units per em
//! for a fixed set of Unicode ranges, an average for every other code point, three vertical
//! metrics and the sha256 of the two font files. Integers only; two runs write identical bytes.

use std::fmt::Write as _;
use std::process::exit;

use sha2::{Digest, Sha256};
use skrifa::raw::TableProvider;
use skrifa::{FontRef, MetadataProvider};

const USAGE: &str = "usage: gen-font-widths --ttf PATH --woff2 PATH (--out FILE | --check FILE)";

/// The sentinel for a code point the font does not map.
const MISSING: u16 = u16::MAX;

/// The column rustfmt fills a long array of numbers to, comma included (a line is at most 99).
const MAX_WIDTH: usize = 99;

/// The ranges, inclusive, in the order the table holds them.
const RANGES: [(u32, u32); 8] = [
    (0x0020, 0x007E), // Basic Latin (printable)
    (0x00A0, 0x00FF), // Latin-1 Supplement
    (0x0100, 0x017F), // Latin Extended-A
    (0x0180, 0x024F), // Latin Extended-B
    (0x0370, 0x03FF), // Greek and Coptic
    (0x0400, 0x04FF), // Cyrillic
    (0x1E00, 0x1EFF), // Latin Extended Additional
    (0x2000, 0x206F), // General Punctuation
];

fn fail(message: &str) -> ! {
    eprintln!("gen-font-widths: {message}");
    exit(1);
}

fn hex(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(64);
    for b in Sha256::digest(bytes) {
        write!(s, "{b:02x}").expect("writing to a String");
    }
    s
}

/// `v` (non-negative) scaled from `upm` units per em to 1,000, rounding half up.
fn scale(v: u64, upm: u64) -> u64 {
    (v * 1000 + upm / 2) / upm
}

fn generate(ttf: &[u8], woff2: &[u8]) -> String {
    let font = FontRef::new(ttf).unwrap_or_else(|_| fail("the TTF does not parse"));
    let head = font
        .head()
        .unwrap_or_else(|_| fail("the font has no head table"));
    let hhea = font
        .hhea()
        .unwrap_or_else(|_| fail("the font has no hhea table"));
    let hmtx = font
        .hmtx()
        .unwrap_or_else(|_| fail("the font has no hmtx table"));
    let os2 = font
        .os2()
        .unwrap_or_else(|_| fail("the font has no OS/2 table"));
    let charmap = font.charmap();
    let upm = u64::from(head.units_per_em());
    if upm == 0 {
        fail("the font has no units per em");
    }

    let advance = |cp: u32| -> u16 {
        let ch = char::from_u32(cp).expect("every code point of the ranges is a char");
        match charmap.map(ch) {
            None => MISSING,
            Some(glyph) => {
                let units = hmtx
                    .advance(glyph)
                    .unwrap_or_else(|| fail("a glyph has no advance"));
                let scaled = scale(u64::from(units), upm);
                if scaled >= u64::from(u16::MAX) {
                    fail("an advance does not fit the table");
                }
                scaled as u16
            }
        }
    };

    let tables: Vec<Vec<u16>> = RANGES
        .iter()
        .map(|&(first, last)| (first..=last).map(advance).collect())
        .collect();

    let (sum, n) = tables[0]
        .iter()
        .filter(|&&v| v != MISSING)
        .fold((0u64, 0u64), |(s, n), &v| (s + u64::from(v), n + 1));
    if n == 0 {
        fail("no printable ASCII character is in the font");
    }
    let average = (sum + n / 2) / n;

    let ascent = scale(
        u64::try_from(hhea.ascender().to_i16()).unwrap_or_else(|_| fail("a negative ascender")),
        upm,
    );
    let descent = scale(
        u64::try_from(-i32::from(hhea.descender().to_i16()))
            .unwrap_or_else(|_| fail("a positive descender")),
        upm,
    );
    if os2.version() < 2 {
        fail("the font has no OS/2 cap height");
    }
    let cap_height = scale(
        u64::try_from(
            os2.s_cap_height()
                .unwrap_or_else(|| fail("the font has no OS/2 cap height")),
        )
        .unwrap_or_else(|_| fail("a negative cap height")),
        upm,
    );

    let mut out = String::new();
    out.push_str(
        "// @generated by tools/gen-font-widths from Inter 4.1 (Inter-Regular.ttf). Do not edit:\n\
         // run tools/gen-font-widths/fetch-inter.sh, then the generator (see its Cargo.toml).\n\n\
         //! Inter 4.1 Regular's advance widths, at 1,000 units per em.\n\n",
    );
    let _ = write!(
        out,
        "/// The font family the diagrams name and the theme serves.\n\
         pub const FONT_FAMILY: &str = \"Inter\";\n\
         /// The release the widths were measured from.\n\
         pub const FONT_VERSION: &str = \"4.1\";\n\
         /// The sha256 of the TTF the widths were measured from.\n\
         pub const FONT_TTF_SHA256: &str =\n    \"{}\";\n\
         /// The sha256 of the woff2 the theme serves (the same release).\n\
         pub const FONT_WOFF2_SHA256: &str =\n    \"{}\";\n\
         /// Units per em of every value below.\n\
         pub const UNITS_PER_EM: u32 = 1000;\n\
         /// The ascender, above the baseline.\n\
         pub const ASCENT: u16 = {ascent};\n\
         /// The descender, below the baseline (positive).\n\
         pub const DESCENT: u16 = {descent};\n\
         /// The height of a capital letter.\n\
         pub const CAP_HEIGHT: u16 = {cap_height};\n\
         /// The advance of any code point outside `RANGES`, and of one the font does not map.\n\
         pub const AVERAGE: u16 = {average};\n\
         /// Not in the font: [`AVERAGE`] is used.\n\
         pub const MISSING: u16 = u16::MAX;\n\n\
         /// `(first, last, advances)`: one advance per code point, `first..=last`.\n\
         pub(crate) const RANGES: [(u32, u32, &[u16]); {}] = [\n",
        hex(ttf),
        hex(woff2),
        RANGES.len(),
    );
    for (&(first, last), values) in RANGES.iter().zip(&tables) {
        let _ = writeln!(
            out,
            "    (\n        0x{first:04X},\n        0x{last:04X},\n        &["
        );
        // Filled the way rustfmt fills a long array of numbers.
        let mut line = String::new();
        for &v in values {
            let cell = if v == MISSING {
                "MISSING".to_string()
            } else {
                v.to_string()
            };
            if !line.is_empty() && 12 + line.len() + 2 + cell.len() + 1 > MAX_WIDTH {
                let _ = writeln!(out, "            {line},");
                line.clear();
            }
            if !line.is_empty() {
                line.push_str(", ");
            }
            line.push_str(&cell);
        }
        if !line.is_empty() {
            let _ = writeln!(out, "            {line},");
        }
        out.push_str("        ],\n    ),\n");
    }
    out.push_str("];\n");
    out
}

enum Mode {
    Out(String),
    Check(String),
}

fn parse(args: &[String]) -> Option<(String, String, Mode)> {
    let (mut ttf, mut woff2, mut mode) = (None, None, None);
    let mut it = args.iter();
    while let Some(flag) = it.next() {
        let value = it.next()?.clone();
        match flag.as_str() {
            "--ttf" if ttf.is_none() => ttf = Some(value),
            "--woff2" if woff2.is_none() => woff2 = Some(value),
            "--out" if mode.is_none() => mode = Some(Mode::Out(value)),
            "--check" if mode.is_none() => mode = Some(Mode::Check(value)),
            _ => return None,
        }
    }
    Some((ttf?, woff2?, mode?))
}

fn read(path: &str) -> Vec<u8> {
    std::fs::read(path).unwrap_or_else(|e| fail(&format!("cannot read {path}: {e}")))
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let Some((ttf, woff2, mode)) = parse(&args) else {
        eprintln!("{USAGE}");
        exit(2);
    };
    let text = generate(&read(&ttf), &read(&woff2));
    match mode {
        Mode::Out(path) => {
            std::fs::write(&path, text)
                .unwrap_or_else(|e| fail(&format!("cannot write {path}: {e}")));
        }
        Mode::Check(path) => {
            if read(&path) != text.as_bytes() {
                eprintln!("gen-font-widths: {path} is not what the generator writes");
                exit(1);
            }
        }
    }
}
