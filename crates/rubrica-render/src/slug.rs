//! The Wiki.js 2 heading-id slugger: uslug@1.0.4-exact (as Wiki.js 2.5.314
//! calls it), then Wiki.js's own `h-` guard and per-page dedupe
//! (`server/modules/rendering/html-core/renderer.js`), and DOMPurify 3.3.1's
//! clobber filter (`html-security/renderer.js`).
//!
//! [`uslug`] is a port of uslug's `lib/uslug.js` with its default options:
//!
//! 1. NFKC, as `unorm@1.6.0` computes it: the `unicode-normalization` crate,
//!    except at the code points where unorm's older Unicode data (it knows
//!    Unicode 7's marks; the exact set is determined empirically, by running
//!    it) and its one-too-long Hangul range disagree with the crate's: one
//!    whose NFKC alone differs takes unorm's result from `UNORM_NFKC`, and one
//!    whose canonical combining class differs (a mark unorm has no data for,
//!    so a starter to it) is left as it is; both split the text, as unorm's
//!    starters do, into separately normalised segments (tables generated);
//! 2. walk the result; uslug walks UTF-16 code units, so anything above
//!    U+FFFF (both surrogate halves) matches nothing and is dropped;
//! 3. keep U+4E00..=U+9FFF and U+AC00..=U+D7A3; U+3000..=U+3002 and
//!    U+FF01..=U+FF02 add a space; keep `-`, `_`, `~`; keep what uslug's own
//!    L, N or M tables list (Unicode-6-era, BMP part vendored as
//!    `uslug_tables`), so letters added to Unicode since are dropped; a code
//!    point in its Z table (19 of them) becomes a space; everything else,
//!    including tab, LF, CR, VT, FF and U+FEFF, is deleted;
//! 4. trim spaces, turn every run of spaces and `-` into one `-`;
//! 5. lowercase, as JS `toLowerCase` does: locale-independent full Unicode,
//!    with Final_Sigma. Rust's [`str::to_lowercase`] implements the same rules.
//!
//! The `h-` prefix is for a leading ASCII digit only (JS `/^\d/`); a duplicate
//! gets `-1`, `-2`, ... (the first free one), and the id is recorded as seen
//! *before* DOMPurify looks at it, so a dropped id still consumes its slot.
//!
//! Proven against the real packages by `tests/uslug_differential.rs` (14,497
//! inputs, generated by `tools/gen-uslug-differential.js`, and every code
//! point in five contexts by digest) and against every heading of the Wiki.js
//! oracle by `tests/oracle_slug.rs`.
//!
//! Unicode versions: the lowercasing is the toolchain's (Rust's
//! `to_lowercase`) and uslug's is the Wiki.js Node's (V8's, from ICU), and the
//! two must have the same Unicode version, 17: `"ΑΣʕΒ"` is `ασʕβ` under 16
//! and `αςʕβ` under 17. A unit test pins `char::UNICODE_VERSION`. The
//! normalisation does not depend on either: unorm is plain JS with its own
//! data. The `unicode-normalization` crate is Unicode 18 (pinned, and a unit
//! test pins its `UNICODE_VERSION`), and it is reconciled with unorm only
//! through the generated tables above: `UNORM_NFKC`, `UNORM_CCC` and
//! `UNORM_NO_COMPOSE`.
//!
//! Composites newer than unorm's data are reachable from a slug: all 21 lie
//! above U+FFFF, but two of them take the BMP U+0307 as their second
//! component (U+105D2 + U+0307 is U+105C9), so composing would drop a mark
//! uslug keeps. They are split at their first component; a unit test walks
//! every composite the crate knows, so a crate bump that adds one fails until
//! the tables are regenerated.
//!
//! The segmented NFKC equals unorm's for every input given five conditions
//! over every code point (a cold review's proof), and each is a unit test: an
//! unsplit code point has unorm's full NFKD (by digest, against the test-only
//! `UNORM_SPLIT` and `UNORM_NFKD_SHA256`), with unorm's classes and no
//! `UNORM_NO_COMPOSE` character in it; the compositions agree; and every split
//! point is inert in unorm.
//!
//! Not here: Wiki.js also honours a custom `{#id}` (markdown-it-attrs)
//! verbatim instead of the slug, still applying the `h-` guard and dedupe
//! (renderer.js ~204-208), and DOMPurify drops it as written, camelCase names
//! included. The corpus uses none (its one `{#` is `${#SECRET}` in a code
//! block), so Rubrica does not support custom ids: `{#id}` is heading text.
//! Wiki.js's treatment differs, and the parity check allows it.

use std::collections::{HashMap, HashSet};

use unicode_normalization::char::{canonical_combining_class, decompose_canonical};
use unicode_normalization::UnicodeNormalization;

pub use crate::dom_clobber::DOM_CLOBBER;
use crate::uslug_tables::{L, M, N, UNORM_CCC, UNORM_NFKC, UNORM_NO_COMPOSE, Z};

fn in_table(table: &[(u16, u16)], c: u16) -> bool {
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < c {
                std::cmp::Ordering::Less
            } else if lo > c {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// unorm's NFKC of `c` alone: its table entry, else `c` itself.
fn unorm_alone(c: char) -> Option<&'static str> {
    UNORM_NFKC
        .binary_search_by_key(&c, |&(d, _)| d)
        .ok()
        .map(|i| UNORM_NFKC[i].1)
}

/// unorm's canonical combining class of `c`: its table entry, else 0 (a
/// starter). Only meaningful for a code point not in `UNORM_NFKC`.
fn unorm_ccc(c: char) -> u8 {
    UNORM_CCC
        .binary_search_by_key(&c, |&(d, _)| d)
        .map_or(0, |i| UNORM_CCC[i].1)
}

/// Whether `c` is, or canonically decomposes to something starting with, the
/// first component of a composite the crate forms and unorm does not
/// (`UNORM_NO_COMPOSE`). unorm composes nothing with such a code point.
fn starts_a_composite_unorm_lacks(c: char) -> bool {
    let mut first = None;
    decompose_canonical(c, |d| {
        first.get_or_insert(d);
    });
    UNORM_NO_COMPOSE.binary_search(&first.unwrap_or(c)).is_ok()
}

/// Whether the slugger splits the text at `c`: the crate and unorm disagree
/// on it alone, so it is not normalised by the crate. That is when:
///
/// - its NFKC alone differs (a character newer than unorm's data, which unorm
///   leaves as it is, or U+D7A4, which unorm's Hangul range wrongly
///   includes): it gets unorm's result;
/// - its canonical combining class differs (a combining mark newer than
///   unorm's data, a starter to unorm): it is kept as it is. Without this the
///   crate would compose across it (`e` U+1DFA U+0301 to `é` U+1DFA) and
///   reorder marks around it, where unorm does neither;
/// - it starts a canonical composite newer than unorm's data
///   (`UNORM_NO_COMPOSE`, e.g. U+105D2, which the crate composes with U+0307
///   to U+105C9): it is kept as it is, so the crate cannot compose it with
///   what follows, as unorm does not.
///
/// In each case the code point is a starter with no composition to unorm, so
/// it splits the text into separately normalised segments. A code point in
/// `UNORM_NFKC` whose results agree is known to both, so their classes agree
/// too (classes are stable once assigned).
fn splits_at(c: char) -> bool {
    let mut buf = [0u8; 4];
    let alone: &str = c.encode_utf8(&mut buf);
    let known = unorm_alone(c);
    let ours: String = alone.nfkc().collect();
    let same_class = known.is_some() || canonical_combining_class(c) == unorm_ccc(c);
    !(ours == known.unwrap_or(alone) && same_class && !starts_a_composite_unorm_lacks(c))
}

/// NFKC as unorm@1.6.0 computes it: the crate's, in segments between the code
/// points it [splits at](splits_at), each of which gets unorm's own result.
fn unorm_nfkc(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut segment = String::new();
    let mut buf = [0u8; 4];
    for c in text.chars() {
        if splits_at(c) {
            out.extend(segment.nfkc());
            segment.clear();
            out.push_str(unorm_alone(c).unwrap_or(c.encode_utf8(&mut buf)));
        } else {
            segment.push(c);
        }
    }
    out.extend(segment.nfkc());
    out
}

/// uslug@1.0.4 with its default options (`allowedChars: "-_~"`, lowercase,
/// no spaces).
pub fn uslug(text: &str) -> String {
    let mut kept = String::with_capacity(text.len());
    for c in unorm_nfkc(text).chars() {
        let Ok(code) = u16::try_from(u32::from(c)) else {
            continue; // above U+FFFF: uslug sees two surrogates, neither kept
        };
        if (0x4E00..=0x9FFF).contains(&code) || (0xAC00..=0xD7A3).contains(&code) {
            kept.push(c);
            continue;
        }
        if (0x3000..=0x3002).contains(&code) || (0xFF01..=0xFF02).contains(&code) {
            kept.push(' ');
        }
        if matches!(c, '-' | '_' | '~') {
            kept.push(c);
            continue;
        }
        if in_table(L, code) || in_table(N, code) || in_table(M, code) {
            kept.push(c);
        } else if in_table(Z, code) {
            kept.push(' ');
        }
    }
    // `.replace(/^\s+|\s+$/g, '')`, then `/\s+/` -> ' ' and `/[\s\-]+/` -> '-'.
    // Only ' ' can be JS whitespace here: nothing uslug keeps is.
    let mut slug = String::with_capacity(kept.len());
    for c in kept.trim_matches(' ').chars() {
        if c == ' ' || c == '-' {
            if !slug.ends_with('-') {
                slug.push('-');
            }
        } else {
            slug.push(c);
        }
    }
    slug.to_lowercase()
}

/// A heading's id, and whether DOMPurify drops it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HeadingId {
    /// The slug, prefixed and deduplicated within the page.
    pub id: String,
    /// True when DOMPurify deletes the attribute: the rendered heading has no
    /// `id` and cannot be linked to, whatever fragment is written.
    pub dropped: bool,
}

/// Per-page dedupe state: one per page, fed its headings in document order.
#[derive(Debug, Default)]
pub struct Slugs {
    seen: HashSet<String>,
    /// Per base slug, the suffix to probe first: every suffix below it was
    /// taken when it was last probed, and `seen` only grows.
    next_suffix: HashMap<String, u32>,
    /// `seen` lookups made for `-N` suffixes, for the cost test.
    probes: u64,
}

impl Slugs {
    /// A fresh page.
    pub fn new() -> Self {
        Self::default()
    }

    /// The id Wiki.js 2 gives the next heading of this page, whose rendered
    /// text is `text`.
    pub fn heading_id(&mut self, text: &str) -> HeadingId {
        let mut slug = uslug(text);
        if slug.as_bytes().first().is_some_and(u8::is_ascii_digit) {
            slug.insert_str(0, "h-");
        }
        if self.seen.contains(&slug) {
            // Wiki.js probes `-1`, `-2`, … from 1 every time (quadratic in
            // the duplicates); starting from the hint finds the same suffix,
            // the smallest free one, since the probe still checks `seen`.
            let next = self.next_suffix.entry(slug.clone()).or_insert(1);
            while {
                self.probes += 1;
                self.seen.contains(&format!("{slug}-{next}"))
            } {
                *next += 1;
            }
            slug = format!("{slug}-{next}");
            *next += 1;
        }
        self.seen.insert(slug.clone());
        let dropped = DOM_CLOBBER.binary_search(&slug.as_str()).is_ok();
        HeadingId { id: slug, dropped }
    }
}

#[cfg(test)]
