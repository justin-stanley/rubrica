#!/usr/bin/env node
// Generates crates/rubrica-render/src/dom_clobber.rs: every `id` value that
// DOMPurify 3.3.1 deletes from a heading under jsdom 16.4.0, with the config
// Wiki.js 2.5.314 sanitizes with (server/modules/rendering/html-security/
// renderer.js: ADD_ATTR, ADD_TAGS, HTML_INTEGRATION_POINTS; SANITIZE_DOM is
// on by default). DOMPurify's rule (purify.cjs.js `_isValidAttribute`) is
// `value in document || value in formElement`, i.e. any property name on
// either prototype chain, Object.prototype included. The candidates are every
// own property name along both chains; each is then confirmed by actually
// sanitizing `<h2 id="NAME">` and checking the attribute is gone, and a
// control set of ordinary slugs is confirmed to survive.
//
// Run by hand from a scratch dir (the JS never enters the repo or the binary):
//
//   mkdir /tmp/clobber && cd /tmp/clobber && npm init -y >/dev/null
//   npm install --no-save dompurify@3.3.1 jsdom@16.4.0
//   node <rubrica>/tools/gen-dom-clobber.js <rubrica>
'use strict';
const fs = require('fs');
const path = require('path');

const repo = process.argv[2];
if (!repo) throw new Error('usage: gen-dom-clobber.js <rubrica checkout>');
const from = (m) => require(require.resolve(m, { paths: [process.cwd()] }));
for (const [m, v] of [['dompurify', '3.3.1'], ['jsdom', '16.4.0']]) {
  const got = JSON.parse(fs.readFileSync(path.join(process.cwd(), 'node_modules', m, 'package.json'), 'utf8')).version;
  if (got !== v) throw new Error(`${m} is ${got}, want ${v}`);
}
const { JSDOM } = from('jsdom');
const createDOMPurify = from('dompurify');

// Wiki.js's html-security renderer, without the optional drawio/iframe extras
// (neither touches `id` handling).
const window = new JSDOM('').window;
const DOMPurify = createDOMPurify(window);
const config = {
  ADD_ATTR: ['v-pre', 'v-slot:tabs', 'v-slot:content', 'target'],
  ADD_TAGS: ['tabset', 'template'],
  HTML_INTEGRATION_POINTS: { foreignobject: true },
};
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
function dropped(id) {
  const out = DOMPurify.sanitize(`<h2 id="${esc(id)}">x</h2>`, config);
  const doc = new JSDOM(`<body>${out}</body>`).window.document;
  const h = doc.querySelector('h2');
  if (!h) throw new Error(`heading vanished for ${id}`);
  return !h.hasAttribute('id');
}

const names = new Set();
for (let o of [window.document, window.document.createElement('form')]) {
  for (; o; o = Object.getPrototypeOf(o)) for (const n of Object.getOwnPropertyNames(o)) names.add(n);
}
const list = [...names].filter(dropped).sort();
const missed = [...names].filter((n) => !dropped(n));
for (const ok of ['architecture', 'the-shape-of-it', 'open-items', 'h-4-x', 'x-1', '', 'styles', 'Style']) {
  if (dropped(ok)) throw new Error(`control ${ok} was dropped`);
}

const lower = list.filter((n) => n === n.toLowerCase()).length;
let body = `// @generated by tools/gen-dom-clobber.js. Do not edit.
//
// Every \`id\` DOMPurify 3.3.1 (SANITIZE_DOM, Wiki.js 2.5.314's config) deletes
// under jsdom 16.4.0 on Node ${process.version}: ${list.length} names, ${lower} of them all-lowercase.
// The comparison is exact (case-sensitive), as JS \`in\` is.

/// Ids DOMPurify refuses to emit because they name a property of \`document\` or
/// of an \`HTMLFormElement\` (prototype chains included). Sorted.
pub const DOM_CLOBBER: &[&str] = &[\n`;
for (const n of list) body += `    ${JSON.stringify(n)},\n`;
body += '];\n';
const out = path.join(repo, 'crates/rubrica-render/src/dom_clobber.rs');
fs.writeFileSync(out, body);
console.log(`wrote ${out}: ${list.length} names (${lower} lowercase); ${missed.length} candidates survived: ${missed.join(' ')}`);
