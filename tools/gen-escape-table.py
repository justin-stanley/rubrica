#!/usr/bin/env python3
"""Generates crates/rubrica/src/escape_table.rs: the code points the text
report escapes beyond the controls and the line and paragraph separators
(crates/rubrica/src/report.rs `hostile`), as sorted inclusive ranges:
general category Cf (Python's unicodedata) and Default_Ignorable_Code_Point
(DerivedCoreProperties.txt), merged. Both must be the same Unicode version,
which is written into the file and pinned by a test. Needs Python 3.15 or
later, whose unicodedata is Unicode 17 (an older Python is refused: its
version does not match the file's). The DerivedCoreProperties.txt read must
be Unicode 17.0.0's, whose sha256 is pinned below (DCP_SHA256) and checked.
Not a build step; run by hand, needing no package:

  curl --proto '=https' -sSfLO https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt
  python3 tools/gen-escape-table.py <rubrica checkout> DerivedCoreProperties.txt
"""
import hashlib
import re
import sys
import unicodedata

# sha256 of DerivedCoreProperties-17.0.0.txt, from unicode.org.
DCP_SHA256 = "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08"

if len(sys.argv) != 3:
    raise SystemExit("usage: gen-escape-table.py <rubrica checkout> <DerivedCoreProperties.txt>")
repo, dcp = sys.argv[1], sys.argv[2]
version = unicodedata.unidata_version

with open(dcp, "rb") as fh:
    raw = fh.read()
got = hashlib.sha256(raw).hexdigest()
if got != DCP_SHA256:
    raise SystemExit("%s has sha256 %s, not DerivedCoreProperties-17.0.0.txt's %s" % (dcp, got, DCP_SHA256))
text = raw.decode("utf-8")
first = text.splitlines()[0]
if first != "# DerivedCoreProperties-%s.txt" % version:
    raise SystemExit("%s is %r, not Unicode %s (Python's)" % (dcp, first, version))

escaped = set()
for c in range(0x110000):
    if not (0xD800 <= c <= 0xDFFF) and unicodedata.category(chr(c)) == "Cf":
        escaped.add(c)
cf = len(escaped)
di = 0
for line in text.splitlines():
    m = re.match(r"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*Default_Ignorable_Code_Point\b", line)
    if m:
        a = int(m.group(1), 16)
        b = int(m.group(2) or m.group(1), 16)
        di += b - a + 1
        escaped.update(range(a, b + 1))
if di == 0:
    raise SystemExit("%s has no Default_Ignorable_Code_Point" % dcp)

ranges = []
for c in sorted(escaped):
    if ranges and ranges[-1][1] == c - 1:
        ranges[-1][1] = c
    else:
        ranges.append([c, c])

out = []
out.append("// @generated by tools/gen-escape-table.py under Python %s (Unicode %s); do not edit."
           % (sys.version.split()[0], version))
out.append("//! The format (Cf) and default-ignorable characters the text report")
out.append("//! escapes.")
out.append("")
out.append("/// The Unicode version the table came from, pinned by a test.")
out.append("#[cfg(test)]")
out.append('pub(crate) const UNICODE_VERSION: &str = "%s";' % version)
out.append("")
out.append("/// General category Cf and Default_Ignorable_Code_Point, as sorted,")
out.append("/// disjoint, non-adjacent inclusive ranges.")
out.append("pub(crate) const ESCAPED: &[(u32, u32)] = &[")
for a, b in ranges:
    out.append("    (0x%04X, 0x%04X)," % (a, b))
out.append("];")
out.append("")

path = repo + "/crates/rubrica/src/escape_table.rs"
with open(path, "w", encoding="utf-8") as fh:
    fh.write("\n".join(out))
print("%s: %d ranges, %d code points (%d Cf, %d Default_Ignorable_Code_Point; Unicode %s)"
      % (path, len(ranges), len(escaped), cf, di, version))
