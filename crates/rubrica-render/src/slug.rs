    /// uslug lowercases last, with JS `String.prototype.toLowerCase`:
    /// locale-independent full Unicode lowercasing, SpecialCasing's
    /// unconditional mappings plus the Final_Sigma context (ECMA-262
    /// `String.prototype.toLowerCase`, "the Unicode Default Case Conversion
    /// algorithm"). Rust's `str::to_lowercase` implements the same two rules.
    /// Every expectation below is what the real uslug@1.0.4 returned under
    /// Node v26.12.0 (V8, ICU 78.3, Unicode 17.0) on 2026-10-26; the NFKC step
    /// before it is why `ǅ` and `ﬀ` come out decomposed.
    #[test]
    fn lowercase_matches_js_on_dotted_capital_i_and_final_sigma() {
        // U+0130 lowercases to "i" + U+0307 COMBINING DOT ABOVE (two code
        // points), and the mark survives the keep set.
        assert_eq!(uslug("\u{0130}"), "i\u{0307}");
        assert_eq!(uslug("\u{0130}stanbul"), "i\u{0307}stanbul");
        // Final sigma is decided on the whole heading, before the split.
        assert_eq!(uslug("ΟΔΟΣ ΟΔΟΣ"), "οδος-οδος");
        assert_eq!(uslug("Σ"), "σ"); // not preceded by a cased letter
        assert_eq!(uslug("ΑΣ1"), "ας1"); // a digit is not cased
        assert_eq!(uslug("ΑΣ-Β"), "ας-β"); // "-" is not case-ignorable
        assert_eq!(uslug("ΑΣ\u{00A0}Β"), "ας-β"); // NBSP neither
        assert_eq!(uslug("ΑΣ.Β"), "ασβ"); // "." is case-ignorable: not final
        assert_eq!(uslug("ΑΣ'Β"), "ασβ"); // so is "'"
                                          // No case folding (ẞ stays a sharp s), but NFKC decomposition.
        assert_eq!(uslug("ẞ"), "ß");
        assert_eq!(uslug("ǅ"), "d\u{17E}"); // NFKC: "D" + "ž", then lowercased
        assert_eq!(uslug("\u{212A}"), "k"); // KELVIN SIGN
        assert_eq!(uslug("\u{2126}"), "ω"); // OHM SIGN
        assert_eq!(uslug("ﬀ"), "ff");
        assert_eq!(uslug("ᾈ"), "ᾀ");
    }

