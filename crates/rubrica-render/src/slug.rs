    #[test]
    fn unorm_is_reproduced_where_its_older_data_differs() {
        // Unicode 12's U+32FF SQUARE ERA NAME REIWA: unorm leaves it alone and
        // uslug drops it (ICU would give 令和).
        assert_eq!(uslug("a\u{32FF}b"), "ab");
        // unorm's Hangul range is one too long: U+D7A4 (not a syllable)
        // decomposes to U+1113 U+1161, both letters in uslug's table.
        assert_eq!(uslug("a\u{D7A4}b"), "a\u{1113}\u{1161}b");
    }

    /// A combining mark newer than unorm's data is a starter to unorm (class
    /// 0), so it blocks composition and reordering there, and uslug then drops
    /// it; the crate knows its real class and composes or reorders across it.
    /// Every expectation is the real uslug@1.0.4's.
    #[test]
    fn a_mark_newer_than_unorm_blocks_composition_and_reordering_like_unorm() {
        // U+1DFA (class 218, Unicode 14): "e" + U+0301 do not compose across it.
        assert_eq!(uslug("e\u{1DFA}\u{301}"), "e\u{301}");
        // U+1ABF (class 220, Unicode 13).
        assert_eq!(uslug("Cafe\u{1ABF}\u{301}"), "cafe\u{301}");
        // Nor are U+0301 (230) and U+0316 (220) reordered across U+1DFA.
        assert_eq!(uslug("q\u{301}\u{1DFA}\u{316}"), "q\u{301}\u{316}");
        // Above U+FFFF too: U+1E944 (Adlam, class 230, Unicode 9) is dropped by
        // uslug, but blocks composition before it is.
        assert_eq!(uslug("e\u{1E944}\u{301}"), "e\u{301}");
    }

    /// uslug's lowercasing is JS `toLowerCase`, which follows the runtime's
    /// Unicode version (ICU's); Rust's `to_lowercase` follows the toolchain's.
    /// They change slugs: "ΑΣʕΒ" is "ασʕβ" under Unicode 16 and "αςʕβ" under
    /// 17, where U+0295 stopped being Cased (so the sigma became final). Wiki.js
    /// runs Node 24.15 with ICU 78 (Unicode 17), and the differential fixture
    /// is generated under Unicode 17. If this fails, the toolchain moved to
    /// another Unicode version: regenerate the fixture under a Node with the
    /// same one and check the prod Wiki.js still matches, or pin the toolchain.
    #[test]
    fn the_toolchain_has_the_unicode_version_wikijs_node_has() {
        assert_eq!(
            char::UNICODE_VERSION,
            (17, 0, 0),
            "Rust's Unicode version must match Wiki.js's Node/ICU (Unicode 17)"
        );
        assert_eq!(uslug("ΑΣʕΒ"), "αςʕβ");
    }

    /// Canonical combining classes never change once assigned, so every class
    /// unorm knows is the crate's too: the class split above fires only on
    /// marks unorm has no data for. (A failure here means the probe in
    /// `tools/gen-uslug-tables.js` misread unorm.)
    #[test]
    fn every_class_unorm_knows_is_the_crates() {
        assert!(UNORM_CCC.windows(2).all(|w| w[0].0 < w[1].0), "sorted");
        for &(c, k) in UNORM_CCC {
            assert_eq!(canonical_combining_class(c), k, "U+{:04X}", u32::from(c));
        }
        // unorm knows Unicode 7's marks (U+1AB0) but not Unicode 8's (U+08E3).
        assert_eq!(unorm_ccc('\u{1AB0}'), 230);
        assert_eq!(unorm_ccc('\u{08E3}'), 0);
        assert_eq!(canonical_combining_class('\u{08E3}'), 220);
    }

    /// A canonical composite newer than unorm's data: the crate composes it,
    /// unorm keeps the parts. U+105D2 + U+0307 is U+105C9 and U+105DA + U+0307
    /// is U+105E4 (Vithkuqi, Unicode 14): the crate's composite is above U+FFFF
    /// and dropped, while unorm keeps the BMP U+0307, which uslug keeps. Every
    /// expectation is the real uslug@1.0.4's.
    #[test]
    fn a_composite_newer_than_unorm_is_not_composed() {
        assert_eq!(uslug("x\u{105D2}\u{307}"), "x\u{307}");
        assert_eq!(uslug("\u{105D2}\u{307}"), "\u{307}");
        assert_eq!(uslug("\u{CB}\u{105DA}\u{307} y"), "\u{EB}\u{307}-y");
    }

    fn crate_nfd(c: char) -> String {
        c.to_string().nfd().collect()
    }

    fn first_of(s: &str) -> char {
        s.chars().next().expect("non-empty")
    }

    /// Walks every primary composite the crate knows (a code point that is its
    /// own NFC and decomposes canonically) and checks the slugger forms exactly
    /// the ones unorm forms: one in `UNORM_COMPOSITES` composes as the crate
    /// composes it, and any other is left decomposed, which needs its first
    /// component in `UNORM_NO_COMPOSE`. A crate bump that adds a composite
    /// unorm lacks fails here until `tools/gen-uslug-tables.js` is rerun; it
    /// reads the crate's own composition tables as well as ICU's, so one Node's
    /// ICU does not know yet is found too. Hangul syllables compose
    /// algorithmically in both and are skipped.
    #[test]
    fn every_composite_the_crate_knows_is_formed_only_if_unorm_forms_it() {
        assert!(UNORM_COMPOSITES.windows(2).all(|w| w[0] < w[1]), "sorted");
        assert!(UNORM_NO_COMPOSE.windows(2).all(|w| w[0] < w[1]), "sorted");
        let fixture = fixture_inputs();
        let (mut known, mut newer) = (0usize, Vec::new());
        for c in (0..=0x10FFFFu32).filter_map(char::from_u32) {
            if ('\u{AC00}'..='\u{D7A3}').contains(&c) {
                continue;
            }
            let d = crate_nfd(c);
            if d.chars().count() < 2 || !d.nfc().eq(std::iter::once(c)) {
                continue;
            }
            let hex = u32::from(c);
            if UNORM_COMPOSITES.binary_search(&c).is_ok() {
                known += 1;
                assert!(
                    UNORM_NO_COMPOSE.binary_search(&first_of(&d)).is_err(),
                    "U+{hex:04X}: unorm forms it, but its first component is in UNORM_NO_COMPOSE"
                );
                let ours: String = d.nfkc().collect();
                assert_eq!(unorm_nfkc(&d), ours, "U+{hex:04X} composes in unorm");
            } else {
                newer.push(c);
                assert!(
                    UNORM_NO_COMPOSE.binary_search(&first_of(&d)).is_ok(),
                    "U+{hex:04X}: the crate composes it and unorm does not, but its first \
                     component U+{:04X} is not in UNORM_NO_COMPOSE: rerun gen-uslug-tables.js",
                    u32::from(first_of(&d))
                );
                assert_eq!(unorm_nfkc(&d), d, "U+{hex:04X} must stay decomposed");
                assert!(
                    fixture.contains(&format!("x{d}")),
                    "U+{hex:04X} has no fixture rows"
                );
            }
        }
        assert_eq!(
            known,
            UNORM_COMPOSITES.len(),
            "every unorm composite is the crate's"
        );
        // The 21 of Unicode 13-16 (Node's ICU, Unicode 17, knows them all; the
        // crate's Unicode 18 adds none).
        assert_eq!(newer.len(), 21, "{newer:X?}");
        // Every entry is needed, and none is a component of a unorm composite
        // (splitting there would break that composition).
        for &n in UNORM_NO_COMPOSE {
            assert!(newer.iter().any(|&c| first_of(&crate_nfd(c)) == n));
            assert_eq!((unorm_ccc(n), unorm_alone(n)), (0, None));
            for &u in UNORM_COMPOSITES {
                assert!(!crate_nfd(u).contains(n), "U+{:04X}", u32::from(u));
            }
        }
    }

    /// Every code point: the walks below cover them all.
    fn every_char() -> impl Iterator<Item = char> {
        (0..=0x10FFFFu32).filter_map(char::from_u32)
    }

    /// The canonical pair a primary composite of `UNORM_COMPOSITES` is formed
    /// from, from the crate (whose compositions agree with unorm's on these:
    /// `every_composite_the_crate_knows_is_formed_only_if_unorm_forms_it`).
    fn pair_of(u: char) -> (char, char) {
        let d = crate_nfd(u);
        let second = d.chars().last().expect("non-empty");
        let rest: String = d[..d.len() - second.len_utf8()].nfc().collect();
        let mut rest = rest.chars();
        let first = rest.next().expect("a first component");
        assert!(rest.next().is_none(), "U+{:04X}", u32::from(u));
        assert_eq!(
            unicode_normalization::char::compose(first, second),
            Some(u),
            "U+{:04X}",
            u32::from(u)
        );
        (first, second)
    }

    /// Every code point the slugger leaves to the crate has the same full NFKD
    /// in the crate as in unorm (condition S1 of the fourth review's proof).
    /// The generator predicts the split points from unorm, ICU and the crate's
    /// own tables (`UNORM_SPLIT`), which must be exactly the ones
    /// [`splits_at`] finds, and hashes unorm's NFKD of every other code point,
    /// one line each, `"<hex>\t<nfkd>\n"` (`UNORM_NFKD_SHA256`); the crate's
    /// must hash the same. A mismatch cannot say where: rerun the generator
    /// with its lines written out and diff them against these.
    #[test]
    fn every_unsplit_code_point_has_unorms_nfkd() {
        use sha2::{Digest, Sha256};
        use std::fmt::Write as _;
        assert!(UNORM_SPLIT.windows(2).all(|w| w[0] < w[1]), "sorted");
        let split: Vec<char> = every_char().filter(|&c| splits_at(c)).collect();
        let missing: Vec<_> = split
            .iter()
            .filter(|c| UNORM_SPLIT.binary_search(c).is_err())
            .collect();
        let extra: Vec<_> = UNORM_SPLIT
            .iter()
            .filter(|c| split.binary_search(c).is_err())
            .collect();
        assert!(
            missing.is_empty() && extra.is_empty(),
            "the slugger splits at {missing:X?}, not in UNORM_SPLIT, and not at {extra:X?}, in it: \
             rerun tools/gen-uslug-tables.js"
        );
        let mut hash = Sha256::new();
        let mut line = String::new();
        for c in every_char().filter(|&c| !splits_at(c)) {
            line.clear();
            let nfkd: String = c.to_string().nfkd().collect();
            writeln!(line, "{:x}\t{nfkd}", u32::from(c)).expect("write to a String");
            hash.update(line.as_bytes());
        }
        let digest: String = hash.finalize().iter().map(|b| format!("{b:02x}")).collect();
        assert_eq!(
            digest, UNORM_NFKD_SHA256,
            "the crate's NFKD of the unsplit code points differs from unorm@1.6.0's"
        );
    }

    /// No code point the slugger leaves to the crate decomposes (fully, NFKD)
    /// to a character in `UNORM_NO_COMPOSE`: if one did, the crate could
    /// compose that character with what follows inside a segment, where unorm
    /// composes nothing with it. (Condition S3 of the fourth review's proof
    /// that the segmented NFKC is unorm's.)
    #[test]
    fn no_unsplit_code_point_decomposes_to_a_no_compose_character() {
        let mut n = 0usize;
        for c in every_char().filter(|&c| !splits_at(c)) {
            n += 1;
            for a in c.to_string().nfkd() {
                assert!(
                    UNORM_NO_COMPOSE.binary_search(&a).is_err(),
                    "U+{:04X} decomposes to U+{:04X}, in UNORM_NO_COMPOSE",
                    u32::from(c),
                    u32::from(a)
                );
            }
        }
        assert!(n > 1_000_000, "only {n} unsplit code points");
    }

    /// Every code point the slugger splits at is inert in unorm, so cutting
    /// the text there changes nothing unorm would have done across it: unorm's
    /// result for it alone starts and ends with a starter (so no mark is
    /// reordered across the cut), its first character is the second component
    /// of no composite unorm forms (so nothing before composes with it), and
    /// its last composes with nothing (so nothing after composes with it).
    /// Hangul is algorithmic in unorm: L (U+1100..=U+1112) + V
    /// (U+1161..=U+1175), and an LV syllable (U+AC00..=U+D7A4, its one-too-long
    /// range, with no T) + T (U+11A8..=U+11C2). (Condition S5 of the fourth
    /// review's proof.)
    #[test]
    fn every_split_point_is_inert_in_unorm() {
        let (mut firsts, mut seconds) = (HashSet::new(), HashSet::new());
        for &u in UNORM_COMPOSITES {
            let (a, b) = pair_of(u);
            firsts.insert(a);
            seconds.insert(b);
        }
        let hangul_lv =
            |c: char| ('\u{AC00}'..='\u{D7A4}').contains(&c) && (u32::from(c) - 0xAC00) % 28 == 0;
        let composes_first =
            |c: char| firsts.contains(&c) || ('\u{1100}'..='\u{1112}').contains(&c) || hangul_lv(c);
        let composes_second = |c: char| {
            seconds.contains(&c)
                || ('\u{1161}'..='\u{1175}').contains(&c)
                || ('\u{11A8}'..='\u{11C2}').contains(&c)
        };
        let mut n = 0usize;
        for c in every_char().filter(|&c| splits_at(c)) {
            n += 1;
            let hex = u32::from(c);
            let theirs = unorm_alone(c).map_or_else(|| c.to_string(), str::to_owned);
            // unorm's NFKC is its own NFKC, so `unorm_ccc` is meaningful here.
            for x in theirs.chars() {
                assert_eq!(unorm_alone(x), None, "U+{hex:04X}: U+{:04X}", u32::from(x));
            }
            let first = first_of(&theirs);
            let last = theirs.chars().last().expect("non-empty");
            assert_eq!(unorm_ccc(first), 0, "U+{hex:04X} starts with a mark");
            assert_eq!(unorm_ccc(last), 0, "U+{hex:04X} ends with a mark");
            assert!(
                !composes_second(first),
                "U+{hex:04X}: U+{:04X} composes with what precedes",
                u32::from(first)
            );
            assert!(
                !composes_first(last),
                "U+{hex:04X}: U+{:04X} composes with what follows",
                u32::from(last)
            );
        }
        assert!(n > 300, "only {n} split points");
    }

    /// Every input of `fixtures/uslug-differential.json` (a row is in the
    /// first group that added it, so an input can be in another group).
    fn fixture_inputs() -> HashSet<String> {
        let path = concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/tests/fixtures/uslug-differential.json"
        );
        let bytes = std::fs::read(path).unwrap_or_else(|e| panic!("read {path}: {e}"));
        let fx: serde_json::Value = serde_json::from_slice(&bytes).expect("parse the fixture");
        fx["rows"]
            .as_array()
            .expect("rows")
            .iter()
            .map(|r| r["input"].as_str().expect("input").to_owned())
            .collect()
    }

    /// The `newer-marks` fixture group must cover every mark the crate gives a
    /// class unorm does not, from the crate's view (Unicode 18), not Node's
    /// ICU (Unicode 17, which lacks 34 of them, e.g. U+05C8 and U+1ADE). The
    /// differential test checks each row against the real uslug.
    #[test]
    fn every_mark_newer_than_unorm_has_fixture_rows() {
        let fixture = fixture_inputs();
        let mut n = 0;
        for c in (0..=0x10FFFFu32).filter_map(char::from_u32) {
            if canonical_combining_class(c) == 0
                || unorm_ccc(c) != 0
                || unorm_alone(c).is_some()
                || crate_nfd(c) != c.to_string()
            {
                continue;
            }
            n += 1;
            for input in [
                format!("e{c}\u{301}"),
                format!("e{c}\u{323}"),
                format!("q\u{301}{c}\u{316} x"),
            ] {
                assert!(
                    fixture.contains(&input),
                    "U+{:04X}: no fixture row {input:?}",
                    u32::from(c)
                );
            }
        }
        assert!(n > 200, "only {n} newer marks");
        for c in [
            '\u{5C8}', '\u{5C9}', '\u{1ADE}', '\u{1ADF}', '\u{1AEC}', '\u{1AF0}',
        ] {
            assert!(fixture.contains(&format!("e{c}\u{301}")), "{c:?}");
        }
    }

